isFunction :: Construct -> Bool
isFunction construct = case construct of
    Function {} -> True
    _ -> False

getFunctionReturnType :: Type -> Type
getFunctionReturnType type' = case type' of
    Ir.FunctionT _ rt -> rt
    _ -> undefined

getFunctionParamsType :: Type -> [Type]
getFunctionParamsType type' = case type' of
    Ir.FunctionT params _ -> params
    _ -> undefined

isBorrowedOrOwnedType :: Type -> Bool
isBorrowedOrOwnedType type' = isBorrowedType type' || isOwnedType type'

isBorrowedType :: Type -> Bool
isBorrowedType type' = case type' of
    Ir.BorrowedT _ _ -> True
    _ -> False

isOwnedType :: Ir.Type -> Bool
isOwnedType type' = case type' of
    Ir.OwnedT _ -> True
    _ -> False

